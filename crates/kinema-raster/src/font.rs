#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_have_pixels() {
        for c in ['A', 'Z', '0', '9', '?'] {
            let total: u32 = rows(c).iter().map(|r| r.count_ones()).sum();
            assert!(total > 5, "{c} should have ink, got {total}");
        }
    }

    #[test]
    fn unknown_characters_are_blank() {
        assert_eq!(rows('\u{4e00}'), [0; 7]);
    }

    #[test]
    fn lowercase_maps_to_uppercase() {
        assert_eq!(rows('a'), rows('A'));
    }
}
