//! The P0 bitmap face: 5 x 7 cells, one row per byte, bit 4 is the leftmost pixel.
//!
//! This exists so a still has real letterforms before the shaping engine lands. It is
//! not a text solution: no kerning, no lowercase, no variable axes. The `text` crate
//! replaces it in P2, and `TYPE-FAKE` already refuses synthetics.

pub const GLYPH_W: u8 = 5;
pub const GLYPH_H: u8 = 7;

/// Uppercase, digits and a few marks. Anything else is a blank cell.
